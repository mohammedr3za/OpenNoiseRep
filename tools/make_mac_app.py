#!/usr/bin/env python3
"""Install a double-clickable macOS launcher for this checkout.

Quick start::

    ./venv/bin/python tools/make_mac_app.py              # /Applications/OpenNoiseRep.app
    ./venv/bin/python tools/make_mac_app.py --menubar    # also the menu-bar app

It installs into /Applications, or ~/Applications when that is not writable.

Unlike ``tools/build_app.py`` (a frozen PyInstaller bundle for releases), the
launcher runs the live code and packages of the interpreter that runs this
script, so edits in the checkout show up on the next launch. Rebuild it after
moving the repo or recreating the venv.

The bundle carries a copy of the framework Python binary, so the Dock and the
menu bar show OpenNoiseRep rather than "Python", and an Info.plist with the
Bluetooth usage string macOS requires before it lets an app use BLE. Output goes
to ``~/Library/Logs/OpenNoiseRep.log``. This script never touches the band.
"""
from __future__ import annotations

import argparse
import os
import pathlib
import platform
import plistlib
import shlex
import shutil
import subprocess
import sys
import sysconfig
import tempfile

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

_ID_PREFIX = "local.opennoiserep"
_LSREGISTER = ("/System/Library/Frameworks/CoreServices.framework/Frameworks/"
               "LaunchServices.framework/Support/lsregister")
_BLUETOOTH_WHY = ("OpenNoiseRep reads heart-rate and activity history from your "
                  "Noise REP band over Bluetooth.")

# (bundle name, executable, CLI subcommand, bundle id suffix, menu-bar only)
_GUI = ("OpenNoiseRep", "OpenNoiseRep", "gui", "", False)
_MENUBAR = ("OpenNoiseRep Menu Bar", "OpenNoiseRepMenuBar", "menubar",
            ".menubar", True)

_LAUNCHER = """\
#!/bin/sh
# Generated by tools/make_mac_app.py; rerun it instead of editing this file.
cd "$HOME" || exit 1
exec {python} -m noiserep.cli {command} >>"$HOME/Library/Logs/OpenNoiseRep.log" 2>&1
"""


def _default_dest() -> pathlib.Path:
    system = pathlib.Path("/Applications")
    if os.access(system, os.W_OK):
        return system
    return pathlib.Path.home() / "Applications"


def _parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--dest", type=pathlib.Path, default=_default_dest(),
                   help="install folder (default: /Applications if writable, "
                        "else ~/Applications)")
    p.add_argument("--menubar", action="store_true",
                   help="also install the experimental menu-bar app")
    return p


def _framework_python() -> pathlib.Path | None:
    """The GUI-capable binary inside a framework build, if this is one."""
    exe = (pathlib.Path(sys.base_prefix)
           / "Resources/Python.app/Contents/MacOS/Python")
    return exe if exe.is_file() else None


def _render_icon(icns: pathlib.Path) -> None:
    from PySide6 import QtCore, QtGui

    from noiserep.gui import theme
    from noiserep.gui.menubar import _heart_path

    size = 1024
    img = QtGui.QImage(size, size, QtGui.QImage.Format_ARGB32_Premultiplied)
    img.fill(QtCore.Qt.transparent)
    p = QtGui.QPainter(img)
    p.setRenderHint(QtGui.QPainter.Antialiasing)

    # macOS icon grid: an 824 px rounded square centred on the 1024 canvas.
    tile = QtCore.QRectF(100, 100, 824, 824)
    grad = QtGui.QLinearGradient(tile.topLeft(), tile.bottomLeft())
    grad.setColorAt(0.0, QtGui.QColor(theme.ACCENT))
    grad.setColorAt(1.0, QtGui.QColor(theme.ACCENT_DEEP))
    p.setPen(QtCore.Qt.NoPen)
    p.setBrush(grad)
    p.drawRoundedRect(tile, 185, 185)

    heart = 560
    p.save()
    p.translate((size - heart) / 2, (size - heart) / 2 + 20)
    p.setBrush(QtGui.QColor(theme.ON_ACCENT))
    p.drawPath(_heart_path(heart))
    p.restore()

    pulse = QtGui.QPainterPath(QtCore.QPointF(300, 520))
    for x, y in ((420, 520), (465, 430), (530, 620), (580, 480),
                 (610, 520), (724, 520)):
        pulse.lineTo(x, y)
    pen = QtGui.QPen(QtGui.QColor(theme.ACCENT_DEEP), 34)
    pen.setCapStyle(QtCore.Qt.RoundCap)
    pen.setJoinStyle(QtCore.Qt.RoundJoin)
    p.setPen(pen)
    p.setBrush(QtCore.Qt.NoBrush)
    p.drawPath(pulse)
    p.end()

    with tempfile.TemporaryDirectory() as tmp:
        iconset = pathlib.Path(tmp) / "AppIcon.iconset"
        iconset.mkdir()
        for base in (16, 32, 128, 256, 512):
            for scale, suffix in ((1, ""), (2, "@2x")):
                px = base * scale
                img.scaled(px, px, QtCore.Qt.IgnoreAspectRatio,
                           QtCore.Qt.SmoothTransformation).save(
                    str(iconset / f"icon_{base}x{base}{suffix}.png"))
        subprocess.run(["iconutil", "-c", "icns", "-o", str(icns),
                        str(iconset)], check=True)


def _build(spec: tuple, dest: pathlib.Path, python: pathlib.Path | None,
           site: str, icns: pathlib.Path) -> pathlib.Path:
    name, executable, command, id_suffix, agent = spec
    bundle_id = _ID_PREFIX + id_suffix
    app = dest / f"{name}.app"
    if app.exists():
        info = app / "Contents/Info.plist"
        try:
            owned = plistlib.loads(info.read_bytes()).get(
                "CFBundleIdentifier") == bundle_id
        except (OSError, plistlib.InvalidFileException):
            owned = False
        if not owned:
            sys.exit(f"{app} exists and was not made by this script; "
                     "move it aside first")
        shutil.rmtree(app)

    macos = app / "Contents/MacOS"
    resources = app / "Contents/Resources"
    macos.mkdir(parents=True)
    resources.mkdir()
    shutil.copy2(icns, resources / "AppIcon.icns")

    if python is not None:
        shutil.copy2(python, macos / "python")
        # A pyvenv.cfg makes the copy a venv interpreter, so children started
        # with sys.executable (the GUI's Live button) import the same packages.
        # The .pth hands over to the real venv, whose own .pth files the
        # editable install needs.
        contents = app / "Contents"
        (contents / "pyvenv.cfg").write_text(
            f"home = {pathlib.Path(sys.base_prefix) / 'bin'}\n"
            "include-system-site-packages = false\n"
            f"version = {platform.python_version()}\n")
        bundle_site = contents / pathlib.Path(site).relative_to(sys.prefix)
        bundle_site.mkdir(parents=True)
        (bundle_site / "noiserep-venv.pth").write_text(
            f"import site; site.addsitedir({site!r})\n")
        interpreter = '"$(dirname "$0")/python"'
    else:
        interpreter = shlex.quote(sys.executable)
    launcher = macos / executable
    launcher.write_text(_LAUNCHER.format(python=interpreter, command=command))
    launcher.chmod(0o755)

    from noiserep import __version__

    info = {
        "CFBundleName": name,
        "CFBundleDisplayName": name,
        "CFBundleIdentifier": bundle_id,
        "CFBundleExecutable": executable,
        "CFBundleIconFile": "AppIcon",
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": __version__,
        "CFBundleVersion": __version__,
        "NSHighResolutionCapable": True,
        "NSBluetoothAlwaysUsageDescription": _BLUETOOTH_WHY,
        "NSBluetoothPeripheralUsageDescription": _BLUETOOTH_WHY,
    }
    if agent:
        info["LSUIElement"] = True
    (app / "Contents/Info.plist").write_bytes(plistlib.dumps(info))

    # Ad-hoc signing: the copied binary's Developer ID signature is bound to
    # Python.app's Info.plist, and Apple silicon refuses unsigned binaries.
    # codesign treats a loose file in Contents/ as nested code, so pyvenv.cfg
    # gets its own signature before the bundle is sealed.
    if python is not None:
        subprocess.run(["codesign", "--force", "--sign", "-", "--identifier",
                        bundle_id + ".python", str(macos / "python")],
                       check=True, capture_output=True)
        subprocess.run(["codesign", "--force", "--sign", "-",
                        str(app / "Contents/pyvenv.cfg")],
                       check=True, capture_output=True)
    subprocess.run(["codesign", "--force", "--sign", "-", str(app)],
                   check=True, capture_output=True)
    subprocess.run([_LSREGISTER, "-f", str(app)], check=False)
    return app


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    if sys.platform != "darwin":
        print("make_mac_app.py builds a macOS .app; use `noiserep gui` elsewhere",
              file=sys.stderr)
        return 2
    if sys.prefix == sys.base_prefix:
        print("run this with the venv interpreter, e.g. "
              "./venv/bin/python tools/make_mac_app.py", file=sys.stderr)
        return 2
    try:
        import PySide6  # noqa: F401
    except ImportError:
        print("the gui extras are missing: pip install -e '.[ble,gui]'",
              file=sys.stderr)
        return 2

    python = _framework_python()
    if python is None:
        print("note: not a framework Python build; the Dock will show "
              "\"Python\" instead of OpenNoiseRep", file=sys.stderr)
    site = sysconfig.get_paths()["purelib"]
    args.dest.mkdir(parents=True, exist_ok=True)
    (pathlib.Path.home() / "Library/Logs").mkdir(parents=True, exist_ok=True)

    specs = [_GUI, _MENUBAR] if args.menubar else [_GUI]
    with tempfile.TemporaryDirectory() as tmp:
        icns = pathlib.Path(tmp) / "AppIcon.icns"
        _render_icon(icns)
        for spec in specs:
            print(f"installed {_build(spec, args.dest, python, site, icns)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
